import {chromium} from 'playwright';
import assert from 'node:assert/strict';

const base=process.env.TEST_ORIGIN||'http://127.0.0.1:8765';
const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
const ctx=await browser.newContext({viewport:{width:1320,height:900},serviceWorkers:'block'});
const page=await ctx.newPage();
const errors=[];
page.on('pageerror',e=>errors.push(e.message));
page.on('dialog',async dialog=>dialog.accept());
const verify=(label,yes)=>{assert.ok(yes,label);console.log('PASS',label)};
const envelope=()=>page.evaluate(()=>JSON.parse(localStorage.getItem('lambert_logistics_versions_v1')));
const readQuick=()=>page.locator('#lkQuickDetailBody');
const quick=page.locator('#lkQuickDetailDialog');
const getNode=async id=>{const rec=await envelope();return rec?.draft?.data?.modules?.flatMap(m=>m.nodes).find(n=>n.id===id)??null;};
try{
 await page.goto(base+'/?view=logistics',{waitUntil:'domcontentloaded'});
 await page.locator('#lkModules .lk-canvas-block').first().waitFor({timeout:28000});
 await page.waitForFunction(()=>!document.documentElement.hasAttribute('data-lambert-boot'),null,{timeout:28000});
 const head=page.locator('.lk-canvas-block[data-module="head"]');
 const scan=head.locator('button[data-action="select-node"][data-id="security-scan"]');
 verify('original knowledge version is not written on visit',await page.evaluate(()=>localStorage.getItem('lambert_logistics_knowledge_v1')===null&&localStorage.getItem('lambert_logistics_versions_v1')===null));
 await scan.click();
 verify('clicking small operation opens visible modal',await quick.isVisible());
 verify('quick modal shows correct operation name',await readQuick().locator('h3').innerText()==='安检扫描');
 verify('quick modal has exactly three visible actions',await readQuick().locator('.lk-node-quick-actions button').allInnerTexts().then(x=>x.join('|')==='编辑名称|编辑内容|删除模块'));
 verify('default lock disables all three edits',await readQuick().locator('.lk-node-quick-actions button:disabled').count()===3);
 verify('locked detail provides unlock affordance',await page.locator('#lkQuickUnlock').isVisible());
 await page.locator('#lkQuickUnlock').click();
 verify('unlock enables action trio without dismissing detail',await quick.isVisible()&&await readQuick().locator('.lk-node-quick-actions button:enabled').count()===3);
 verify('unlock preserves the selected security-scan operation',await readQuick().locator('h3').innerText()==='安检扫描');
 await readQuick().locator('button[data-action="rename-node"]').click();
 verify('rename dialog opens directly',await page.locator('#lkRenameNodeDialog').isVisible());
 verify('rename field prefilled',await page.locator('#lkRenameNodeName').inputValue()==='安检扫描');
 await page.locator('#lkRenameNodeName').fill('安检扫描 · 已核实');
 await page.locator('#lkRenameNodeForm button[type="submit"]').click();
 verify('rename result updates immediately and reopens detail',await quick.isVisible()&&await readQuick().locator('h3').innerText()==='安检扫描 · 已核实');
 verify('card label reflects rename',await scan.innerText().then(t=>t.includes('安检扫描 · 已核实')));
 verify('no storage write before manual draft save',await page.evaluate(()=>localStorage.getItem('lambert_logistics_versions_v1')===null));
 verify('existing branch still attached to original stable ID',await readQuick().getByText('安检异常 → 安检异常上报').count()===1);
 await readQuick().locator('button[data-action="edit-node"]').click();
 verify('content editor opens from same quick detail',await page.locator('#lkNodeDialog').isVisible());
 verify('edited name also present in content editor',await page.locator('#lkTitleInput').inputValue()==='安检扫描 · 已核实');
 await page.locator('#lkNoteInput').fill('本次只核实了业务动作，暂未绑定真实事件码');
 await page.locator('#lkTagsInput').fill('安检,扫描');
 await page.locator('#lkCodesInput').fill('DDS');
 await page.locator('#lkNodeForm button[type="submit"]').click();
 verify('content save returns to updated quick detail',await quick.isVisible()&&await readQuick().innerText().then(t=>t.includes('暂未绑定真实事件码')));
 verify('ID and branch still present after rename + content edit',await page.evaluate(()=>{
   const detail=document.querySelector('#lkQuickDetailBody');
   const source=detail?.querySelector('[data-action="branch-add"]');
   const title=document.querySelector('.lk-step[data-drag-node="security-scan"] .lk-canvas-op strong');
   return source?.dataset.id==='security-scan'&&title?.textContent==='安检扫描 · 已核实';
 }));
 await page.locator('#lkQuickClose').click();
 verify('close detail returns to original flow without navigation',!await quick.isVisible()&&await page.locator('#lkProcess').isVisible());
 // Clicking the exception-only operation must work as well.
 await head.locator('.lk-branch-edge button[data-action="select-node"][data-id="security-exception"]').click();
 verify('branch operation opens same three-action detail',await quick.isVisible()&&await readQuick().locator('h3').innerText()==='安检异常上报');
 await readQuick().locator('button[data-action="rename-node"]').click();
 await page.locator('#lkRenameNodeName').fill('异常上报 · 人工复核');
 await page.locator('#lkRenameNodeForm button[type="submit"]').click();
 verify('renamed branch target reflected on original edge',await readQuick().locator('h3').innerText()==='异常上报 · 人工复核');
 await page.locator('#lkQuickClose').click();
 // A disabled deletion must remain safe while editing is unlocked.
 await scan.click();
 await readQuick().locator('button[data-action="node-delete"]').click();
 verify('delete from detail closes the dialog and moves into draft recycle bin',!await quick.isVisible()&&await page.locator('#lkTrashCount').innerText()==='1');
 await page.locator('.lk-trash-panel summary').click();
 await page.locator('#lkTrashList button[data-action="trash-restore"]').click();
 verify('recycled operation restores under the same ID',await scan.count()===1);
 await page.locator('#lkSaveDraft').click();
 const saved=await envelope();
 const old=saved.published.data.modules.find(m=>m.id==='head');
 const edit=saved.draft.data.modules.find(m=>m.id==='head');
 verify('draft keeps original ID plus renamed title and new note',edit.nodes.find(n=>n.id==='security-scan')?.title==='安检扫描 · 已核实'&&edit.nodes.find(n=>n.id==='security-scan')?.note.includes('未绑定真实事件码'));
 verify('the published snapshot is unchanged before publish',old.nodes.find(n=>n.id==='security-scan')?.title==='安检扫描');
 verify('branch references survive both renames',edit.branches.find(b=>b.id==='security-exception-branch')?.from==='security-scan'&&edit.branches.find(b=>b.id==='security-exception-branch')?.to==='security-exception');
 await page.locator('#lkPublish').click();
 verify('published version now includes renames',(await envelope()).published.data.modules[0].nodes.find(n=>n.id==='security-exception').title==='异常上报 · 人工复核');
 await page.locator('#lkModeDetail').click();
 await page.locator('#lkOverview button.lk-ov-link').filter({hasText:'安检扫描 · 已核实'}).first().click();
 verify('clicking small operation in B overview opens same detail',await quick.isVisible()&&await readQuick().locator('h3').innerText()==='安检扫描 · 已核实');
 verify('publishing returns to locked state',await readQuick().locator('.lk-node-quick-actions button:disabled').count()===3);
 // On a narrow viewport, all three actions remain available.
 await page.locator('#lkQuickClose').click();
 await page.setViewportSize({width:390,height:844});
 await page.locator('#lkTabProcess').click();
 await page.locator('.lk-canvas-block[data-module="head"] button[data-action="select-node"][data-id="security-scan"]').click();
 verify('mobile quick actions remain visible',await readQuick().locator('.lk-node-quick-actions button').count()===3&&await quick.isVisible());
 await page.locator('#lkQuickClose').click();
 verify('no uncaught browser errors',errors.length===0);
 console.log('V3.2 quick edit checks passed');
}finally{await browser.close();}
