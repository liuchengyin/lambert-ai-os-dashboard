import {chromium} from 'playwright';
import assert from 'node:assert/strict';
const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
const context=await browser.newContext({viewport:{width:1400,height:900},serviceWorkers:'block'});
const page=await context.newPage();
const errors=[];
page.on('pageerror',e=>errors.push(e.message));
page.on('dialog',d=>d.accept());
const base=process.env.TEST_ORIGIN||'http://127.0.0.1:8765';
const check=(name,condition)=>{assert.ok(condition,name);console.log('PASS:',name)};
const record=()=>page.evaluate(()=>JSON.parse(localStorage.getItem('lambert_logistics_versions_v1')));
try{
 await page.goto(base+'/?view=logistics',{waitUntil:'domcontentloaded'});
 await page.locator('#lkEditStatus').waitFor({timeout:29000});
 await page.waitForFunction(()=>!document.documentElement.hasAttribute('data-lambert-boot'),null,{timeout:29000});
 check('soft pastel middle module background',await page.locator('.lk-substage').first().evaluate(el=>getComputedStyle(el).backgroundColor)==='rgb(246, 242, 255)');
 check('soft lilac shadow rather than black',await page.locator('.lk-canvas-block').first().evaluate(el=>getComputedStyle(el).boxShadow.includes('115, 78, 169')||getComputedStyle(el).boxShadow.includes('113, 69, 172')));
 check('stage pastel backgrounds differ by position',await page.locator('.lk-substage').nth(1).evaluate(el=>getComputedStyle(el).backgroundColor)==='rgb(241, 247, 255)');
 check('old data remains untouched on load',await page.evaluate(()=>!localStorage.getItem('lambert_logistics_knowledge_v1')&&!localStorage.getItem('lambert_logistics_versions_v1')));
 await page.locator('.lk-canvas-block[data-module="head"] button[data-action="select-node"][data-id="security-scan"]').click();
 check('click node opens quick detail',await page.locator('#lkQuickDetailDialog').isVisible());
 await page.locator('#lkQuickUnlock').click();
 await page.locator('#lkQuickDetailBody button[data-action="edit-node"]').click();
 check('simplified editor opens',await page.locator('#lkNodeDialog').isVisible());
 check('obsolete kind/status/evidence fields removed from editing UI',await page.locator('#lkKindInput,#lkConfidenceInput,#lkEvidenceInput,#lkRecordInput,#lkInfoInput').count()===0);
 check('event search honestly disabled until real codebook arrives',await page.locator('#lkEventSearch').isDisabled()&&await page.locator('#lkEventHint').innerText().then(s=>s.includes('码表待导入')));
 check('operation name is already populated',await page.locator('#lkTitleInput').inputValue()==='安检扫描');
 check('legacy operation data displayed separately without modification',await page.locator('#lkExistingCodes').innerText().then(s=>s===''||s.includes('旧码值')));
 await page.locator('#lkAddTrigger').click();
 await page.locator('#lkTriggerRows input').first().fill('产生安检处理结果');
 await page.locator('#lkTriggerRows input').last().fill('更新货件安检状态');
 await page.locator('#lkActionInput').fill('通过设备进行安检扫描');
 await page.locator('#lkNoteInput').fill('操作已复核，但事件码尚未确认');
 await page.locator('#lkTagsInput').fill('安检,设备');
 await page.locator('#lkNodeForm button[type="submit"]').click();
 check('edit returns to operation detail',await page.locator('#lkQuickDetailDialog').isVisible());
 check('multiple trigger outcomes shown in operation detail',await page.locator('#lkQuickDetailBody .lk-trigger-list li').count()===2);
 await page.locator('#lkQuickClose').click();
 check('no accidental persistent write before save draft',await page.evaluate(()=>!localStorage.getItem('lambert_logistics_versions_v1')));
 await page.locator('#lkAddNode').click();
 check('new operation initially has a blank trigger',await page.locator('#lkTriggerRows input').count()===1);
 await page.locator('#lkTitleInput').fill('临时测试操作');
 await page.locator('#lkNodeForm button[type="submit"]').click();
 check('new operation without trigger cannot be saved',await page.locator('#lkNodeDialog').isVisible());
 await page.locator('#lkTriggerRows input').fill('触发系统处理');
 await page.locator('#lkNodeForm button[type="submit"]').click();
 check('new operation with one trigger saves',!await page.locator('#lkNodeDialog').isVisible());
 await page.locator('#lkSaveDraft').click();
 const saved=await record(),m=saved.draft.data.modules.find(x=>x.id==='head'),n=m.nodes.find(x=>x.id==='security-scan');
 check('draft stores both triggers',n.triggers.length===2&&n.triggers[0].description==='产生安检处理结果');
 check('untouched historical source fields and graph ID',n.id==='security-scan'&&typeof n.information==='string'&&m.branches[0].from==='security-scan');
 check('published snapshot unchanged before release',saved.published.data.modules.find(x=>x.id==='head').nodes.find(x=>x.id==='security-scan').triggers===undefined);
 await page.locator('#lkPublish').click();
 check('published version contains new outcomes',(await record()).published.data.modules.find(x=>x.id==='head').nodes.find(x=>x.id==='security-scan').triggers.length===2);
 check('page runtime errors absent',errors.length===0);
 console.log('V3.3 integrated browser checks passed');
}finally{await browser.close();}
