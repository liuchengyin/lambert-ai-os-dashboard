import {chromium} from 'playwright';
import assert from 'node:assert/strict';
const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
const base=process.env.TEST_ORIGIN||'http://127.0.0.1:8765';
const ctx=await browser.newContext({viewport:{width:1280,height:900},serviceWorkers:'block',acceptDownloads:true});
const page=await ctx.newPage(),errors=[];page.on('pageerror',e=>errors.push(e.message));
page.on('dialog',async dialog=>dialog.accept());
const get=key=>page.evaluate(key=>localStorage.getItem(key),key);
const envelope=()=>page.evaluate(()=>JSON.parse(localStorage.getItem('lambert_logistics_versions_v1')));
const pass=(name,yes)=>{assert.ok(yes,name);console.log('PASS:',name)};
try{
 await page.goto(base+'/?view=logistics',{waitUntil:'domcontentloaded'});
 await page.locator('#lkEditStatus').waitFor({timeout:26000});
 await page.waitForFunction(()=>!document.documentElement.hasAttribute('data-lambert-boot'),null,{timeout:26000});
 pass('legacy content initially remains untouched',await get('lambert_logistics_knowledge_v1')===null);
 pass('new version record not written on open',await get('lambert_logistics_versions_v1')===null);
 pass('locked by default',await page.locator('#lkEditStatus').innerText().then(s=>s.includes('已锁定')));
 pass('mutating module controls disabled',await page.locator('#lkAddModule').isDisabled()&&await page.locator('.lk-canvas-block[data-module="head"] input[type="color"][data-color-module="head"]:not([data-color-stage])').isDisabled());
 await page.locator('#lkTabOverview').click();
 pass('third tab shows A macro model by default',await page.locator('#lkModeMacro').getAttribute('aria-pressed')==='true');
 pass('A shows five linked business modules',await page.locator('#lkOverview .lk-ov-module').count()===5);
 pass('A does not unfold detail nodes',await page.locator('#lkOverview .lk-ov-op').count()===0);
 await page.locator('#lkModeDetail').click();
 pass('B shows all four warehouse substages',await page.locator('#lkOverview .lk-ov-stage').count()>=8);
 pass('B shows condition / exception branches',await page.locator('#lkOverview .lk-ov-exception').count()>=1);
 await page.locator('#lkTabProcess').click();
 await page.locator('#lkUnlock').click();
 pass('unlocked enables module changes',await page.locator('#lkAddModule').isEnabled());
 await page.locator('.lk-canvas-block[data-module="head"] input[type="color"][data-color-module="head"]:not([data-color-stage])').fill('#22aabb');
 pass('uncommitted changes not written anywhere',await get('lambert_logistics_versions_v1')===null);
 pass('unsaved indicator and publish blocked',await page.locator('#lkEditStatus').innerText().then(s=>s.includes('未保存'))&&await page.locator('#lkPublish').isDisabled());
 await page.locator('#lkTabOverview').click();
 pass('overview not affected by unsaved edits',await page.locator('.lk-ov-module').first().evaluate(el=>getComputedStyle(el).getPropertyValue('--lk-ov-color').trim())==='#477DBD');
 await page.locator('#lkSaveDraft').click();
 const draft=await envelope();
 pass('save creates separate draft and release',draft.draft.data.modules[0].color==='#22AABB'&&draft.published.data.modules[0].color===undefined&&draft.published.number===0);
 pass('legacy key never modified by save draft',await get('lambert_logistics_knowledge_v1')===null);
 await page.reload({waitUntil:'domcontentloaded'});
 await page.locator('#lkEditStatus').waitFor();
 pass('reload locks even with saved draft',await page.locator('#lkEditStatus').innerText().then(s=>s.includes('已锁定')&&s.includes('草稿')));
 await page.locator('#lkUnlock').click();
 pass('saved draft reopens with modified color',await page.locator('.lk-canvas-block[data-module="head"] input[type="color"][data-color-module="head"]:not([data-color-stage])').inputValue()==='#22aabb');
 pass('publish enabled for saved draft',await page.locator('#lkPublish').isEnabled());
 await page.locator('#lkPublish').click();
 const released=await envelope();
 pass('publishing increments release and preserves baseline',released.published.number===1&&released.published.data.modules[0].color==='#22AABB'&&released.history[0].number===0&&released.draft===null);
 pass('publish relocks and opens overview',await page.locator('#lkEditStatus').innerText().then(s=>s.includes('已锁定'))&&await page.locator('#lkOverview').isVisible());
 pass('overview reflects published color',await page.locator('.lk-ov-module').first().evaluate(el=>getComputedStyle(el).getPropertyValue('--lk-ov-color').trim())==='#22AABB');

 // A second explicit release removes one exception link, then history rollback restores it.
 await page.locator('#lkUnlock').click();
 await page.locator('.lk-canvas-block[data-module="head"] button[data-action="select-node"][data-id="security-scan"]').click();
 await page.locator('#lkDetail button[data-action="branch-remove"]').click();
 await page.locator('#lkSaveDraft').click();
 await page.locator('#lkTabOverview').click();
 await page.locator('#lkModeDetail').click();
 pass('overview still has published branch until publication',await page.locator('#lkOverview .lk-ov-exception').count()>=1);
 await page.locator('#lkPublish').click();
 pass('second release removes exception from published graph',(await envelope()).published.number===2&&!(await envelope()).published.data.modules[0].branches.some(e=>e.id==='security-exception-branch'));
 pass('exception removed in B overview',await page.locator('#lkModeDetail').click().then(()=>page.locator('#lkOverview .lk-ov-exception').count())===0);
 await page.locator('#lkHistorySelect').selectOption('0');
 pass('rollback button available when locked and chosen history',await page.locator('#lkRollback').isEnabled());
 await page.locator('#lkRollback').click();
 const rolled=await envelope();
 pass('rollback creates new published version',rolled.published.number===3&&rolled.published.restoredFrom===0&&rolled.history.length===3);
 pass('rollback restores baseline and retains later history',rolled.published.data.modules[0].color===undefined&&rolled.published.data.modules[0].branches.length===1&&rolled.history.some(h=>h.number===2));
 pass('no uncaught OS runtime errors',errors.length===0);

 // A separate browser context verifies old stored V1 data becomes baseline without rewriting it.
 const other=await browser.newContext({serviceWorkers:'block'});
 const legacy={schema:1,route:'旧线路',modules:[{id:'old',name:'旧中心仓',category:'仓',enabled:true,nodes:[{id:'op',title:'旧扫描',evidence:'原凭证'}]}]};
 await other.addInitScript(data=>localStorage.setItem('lambert_logistics_knowledge_v1',JSON.stringify(data)),legacy);
 const old=await other.newPage();
 await old.goto(base+'/?view=logistics',{waitUntil:'domcontentloaded'});
 await old.locator('#lkEditStatus').waitFor({timeout:26000});
 pass('old V1 record opens as published baseline',await old.locator('#lkModules .lk-canvas-block').count()===1);
 pass('old V1 key remains byte-identical',await old.evaluate(expected=>localStorage.getItem('lambert_logistics_knowledge_v1')===JSON.stringify(expected),legacy));
 await other.close();
 console.log('Version and overview browser regression passed');
}finally{await browser.close();}
