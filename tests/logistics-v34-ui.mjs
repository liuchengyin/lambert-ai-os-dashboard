import {chromium} from 'playwright';
import assert from 'node:assert/strict';
const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
const ctx=await browser.newContext({viewport:{width:1440,height:900},serviceWorkers:'block'});
const page=await ctx.newPage(),errors=[];
page.on('pageerror',error=>errors.push(error.message));
page.on('dialog',dialog=>dialog.accept());
const origin=process.env.TEST_ORIGIN||'http://127.0.0.1:8765';
const check=(name,truth)=>{assert.ok(truth,name);console.log('PASS:',name)};
const saved=()=>page.evaluate(()=>JSON.parse(localStorage.getItem('lambert_logistics_versions_v1')));
try{
 await page.goto(origin+'/?view=logistics',{waitUntil:'domcontentloaded'});
 await page.locator('#lkEditStatus').waitFor({timeout:30000});
 await page.waitForFunction(()=>!document.documentElement.hasAttribute('data-lambert-boot'),null,{timeout:30000});
 check('land sea air toolbar visible',await page.locator('.lk-mode-toolbar button').count()===3);
 check('legacy road linehaul inferred without rewriting',await page.locator('.lk-canvas-block[data-module="linehaul"] .lk-module-main').innerText().then(s=>s.includes('陆运')));
 check('default lock prohibits premature module creation',await page.locator('[data-action="add-linehaul-mode"][data-mode="air"]').isDisabled());
 check('no local knowledge keys written when only viewed',await page.evaluate(()=>localStorage.getItem('lambert_logistics_versions_v1')===null&&localStorage.getItem('lambert_logistics_knowledge_v1')===null));
 await page.locator('#lkUnlock').click();
 await page.locator('[data-action="add-linehaul-mode"][data-mode="air"]').click();
 check('air linehaul template appears as new L2 module',await page.locator('.lk-canvas-block .lk-module-main').filter({hasText:'空运干线'}).count()===1);
 const air=page.locator('.lk-canvas-block').filter({has:page.locator('.lk-module-main',{hasText:'空运干线'})});
 check('air template references exist with blank actual values',await air.locator('.lk-setup-badge').count()===6&&await air.locator('.lk-setup-badge').first().textContent().then(t=>t.includes('待配置')));
 await air.locator('[data-action="setup-module"]').click();
 check('air setup editor lists six screenshot menu entries',await page.locator('#lkSetupRows .lk-setup-row').count()===6);
 check('flight log is reference rather than mandatory prerequisite',await page.locator('#lkSetupRows .lk-setup-row').last().locator('select').inputValue()==='reference');
 check('airport preconfig value blank until user enters it',await page.locator('#lkSetupRows .lk-setup-row').first().locator('input[aria-label="前置配置值"]').inputValue()==='');
 await page.locator('#lkSetupRows .lk-setup-row').first().locator('input[aria-label="前置配置值"]').fill('嘉兴南湖机场');
 await page.locator('#lkSetupForm button[type="submit"]').click();
 check('air setup saved in current draft UI',await air.locator('.lk-setup-badge').count()===6);
 await air.locator('.lk-setup-summary summary').first().click();
 check('config displays the user-provided airport',await air.getByText('机场管理 · 嘉兴南湖机场').count()===1);
 const stage=air.locator('.lk-substage').first();
 await stage.locator('[data-action="setup-stage"]').click();
 check('middle module may also set its own prerequisites',await page.locator('#lkSetupRows .lk-setup-row').count()===0);
 await page.locator('#lkAddSetup').click();
 await page.locator('#lkSetupRows input[aria-label="前置配置名称"]').fill('始发中心复核');
 await page.locator('#lkSetupRows input[aria-label="前置配置值"]').fill('发货前核对机场与航线');
 await page.locator('#lkSetupForm button[type="submit"]').click();
 check('stage prerequisite separately visible',await stage.locator('.lk-setup-stage-summary').count()===1);
 await page.locator('[data-action="add-linehaul-mode"][data-mode="sea"]').click();
 check('sea linehaul can be added independently',await page.locator('.lk-module-main').filter({hasText:'海运干线'}).count()===1);
 check('old road linehaul still contains all prior operations',await page.locator('.lk-canvas-block[data-module="linehaul"]').locator('button[data-action="select-node"]').count()>=5);
 check('unsaved changes have not mutated persisted release',await page.evaluate(()=>localStorage.getItem('lambert_logistics_versions_v1')===null));
 await page.locator('#lkSaveDraft').click();
 const draft=await saved();
 const airM=draft.draft.data.modules.find(m=>m.transportMode==='air');
 check('draft persists air mode and user-provided airport',airM.prerequisites.find(x=>x.name==='机场管理').value==='嘉兴南湖机场');
 check('draft persists middle-stage prerequisites',airM.stages[0].prerequisites.find(x=>x.name==='始发中心复核').value==='发货前核对机场与航线');
 check('published V0 unchanged before release',draft.published.data.modules.every(x=>x.transportMode!=='air'));
 check('old V1 storage key still pristine',await page.evaluate(()=>localStorage.getItem('lambert_logistics_knowledge_v1')===null));
 await page.locator('#lkPublish').click();
 check('published release includes sea/air modes',(await saved()).published.data.modules.some(m=>m.transportMode==='air')&&(await saved()).published.data.modules.some(m=>m.transportMode==='sea'));
 check('A overview lists new air/sea linehauls',await page.locator('#lkOverview .lk-ov-module-head').filter({hasText:'空运干线'}).count()===1);
 const section=page.locator('#lkOverview .lk-ov-module').filter({hasText:'空运干线'});
 await section.locator('.lk-ov-prereq summary').first().click();
 check('overview displays published airport setup',await section.getByText('机场管理 · 嘉兴南湖机场').count()===1);
 await page.locator('#lkModeDetail').click();
 const full=page.locator('#lkOverview .lk-ov-module').filter({hasText:'空运干线'});
 check('B overview shows stage-level setup',await full.locator('.lk-ov-stage .lk-ov-prereq').count()===1);
 check('no browser runtime exceptions',errors.length===0);
 console.log('V3.4 browser regression passed');
}finally{await browser.close();}
