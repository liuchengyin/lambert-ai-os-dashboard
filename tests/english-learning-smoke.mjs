function createWav(seconds){
  const sampleRate=8000,samples=sampleRate*seconds,pcm=Buffer.alloc(samples*2);
  for(let i=0;i<samples;i++)pcm.writeInt16LE(Math.round(Math.sin(2*Math.PI*440*i/sampleRate)*3000),i*2);
  const b=Buffer.alloc(44+pcm.length);
  b.write('RIFF',0);b.writeUInt32LE(36+pcm.length,4);b.write('WAVEfmt ',8);
  b.writeUInt32LE(16,16);b.writeUInt16LE(1,20);b.writeUInt16LE(1,22);
  b.writeUInt32LE(sampleRate,24);b.writeUInt32LE(sampleRate*2,28);
  b.writeUInt16LE(2,32);b.writeUInt16LE(16,34);b.write('data',36);
  b.writeUInt32LE(pcm.length,40);pcm.copy(b,44);return b;
}
